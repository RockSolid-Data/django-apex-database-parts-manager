    def _merge_app_rows(self, pairs: List[Tuple[int, int]]) -> None:
        """Re-point ApplicationUnit links from variant ids onto base ids,
        then delete the variant Application rows.

        `pairs` is a list of (variant_app_id, base_app_id).
        Uses update_or_create to handle (application, unit) collisions.
        """
        # Group by base for batch processing
        by_base: Dict[int, List[int]] = defaultdict(list)
        for var_id, base_id in pairs:
            by_base[base_id].append(var_id)

        for base_id, var_ids in by_base.items():
            for link in list(
                ApplicationUnit.objects.filter(application_id__in=var_ids)
            ):
                defaults = {}
                if link.position:
                    defaults["position"] = link.position
                if link.notes:
                    defaults["notes"] = link.notes
                ApplicationUnit.objects.update_or_create(
                    application_id=base_id,
                    unit_id=link.unit_id,
                    defaults=defaults,
                )
                link.delete()
            Application.objects.filter(id__in=var_ids).delete()

    def _bulk_update_field(
        self, pairs: List[Tuple[int, str]], field: str
    ) -> None:
        for i in range(0, len(pairs), 500):
            batch = pairs[i:i + 500]
            objs = list(
                Application.objects
                .filter(id__in=[p[0] for p in batch])
                .only("id", field)
            )
            value_map = dict(batch)
            for o in objs:
                setattr(o, field, value_map[o.id])
            Application.objects.bulk_update(objs, [field], batch_size=500)
