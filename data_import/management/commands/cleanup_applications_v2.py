"""Round-two Application cleanup that finds duplicate patterns Phase A
(cleanup_normalize_applications) missed.

Runs four passes in a single transaction:

  Step 0  - Whitespace cleanup.  Collapses double-spaces to single spaces
            in `model` (~2,500 rows) and `engine` (~10 rows).  These are
            cosmetic parser artifacts (e.g. 'All Models  1986-1995').

  Step 1  - Make rename map.  Collapses 40+ formatting / spelling
            variants of the same brand to a single canonical spelling
            (e.g. 'GMC' -> 'Gmc', 'Mercedes Benz' -> 'Mercedes-Benz',
            'Bluebird' -> 'Blue Bird', 'Weidmann)' -> the canonical
            full brand name for parser-truncated values).  Pick of
            canonical follows the cross-ref cleanup precedent: the
            more-popular variant wins, with all-caps acronym proper
            nouns preserved where unambiguous.

  Step 2  - Model rename map.  Per-make, fixes the dominant
            'X- Y' -> 'X-Y' parser artifact (extra space after hyphen
            in models like 'F- 150', 'E- 350 Econoline') that came
            from PDF line-break splitting.  Auto-generated by scanning
            for (make, model) pairs where stripping the stray space
            produces an existing canonical model.

  Step 3  - Subset-pair merges (OPT-IN, default disabled).  For each
            configured (BASE_BRAND, VARIANT_BRAND) pair, finds rows
            under VARIANT_BRAND whose (model, engine, year) triple
            already exists under BASE_BRAND, re-points the ApplicationUnit
            links, then deletes the variant row.  Informational mode
            only by default -- prints candidate pairs and overlap counts
            so the user can opt-in pair-by-pair.

  Step 4  - Post-rename dedup.  After all renames, finds groups by
            (make, model, engine, year), keeps the lowest-id canonical,
            re-points every duplicate's ApplicationUnit M2M links to
            the canonical (collapsing collisions via update_or_create),
            and deletes the duplicates.

Usage::

    python manage.py cleanup_applications_v2              # dry-run (default)
    python manage.py cleanup_applications_v2 --dry-run    # explicit
    python manage.py cleanup_applications_v2 --commit     # apply
"""

from __future__ import annotations

import re
import time
from collections import defaultdict
from typing import Dict, List, Tuple

from django.core.management.base import BaseCommand, CommandError
from django.db import transaction

from catalog.models import Application, ApplicationUnit


